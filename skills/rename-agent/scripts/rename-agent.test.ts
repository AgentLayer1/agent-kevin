import { afterAll, describe, expect, test } from 'bun:test';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pluginName, RUNTIME_DIR } from '../../../mcp-server/src/shared/naming';

const SCRIPT = join(import.meta.dir, 'rename-agent.ts');
const dirs: string[] = [];
afterAll(() => {
  for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
});

const IDENTITY =
  '# Identity\n\n## Who\n\n- **Name:** Kevin\n- **Emoji:** 🍌\n- **Vibe:** Inspired by the minion Kevin.\n';

/** A home with prose in every swept place, plus history, generated files and paths that must stay. */
const home = (files: Record<string, string | Buffer> = {}) => {
  const root = mkdtempSync(join(tmpdir(), 'rename-agent-'));
  dirs.push(root);
  const all: Record<string, string | Buffer> = {
    [join(RUNTIME_DIR, 'version.json')]: `${JSON.stringify({ plugin: pluginName() })}\n`,
    'IDENTITY.md': IDENTITY,
    'SOUL.md': "You are Kevin. Kevin's rules.\n",
    'AGENTS.md': '# Kevin\n\nHome at `~/Documents/Agents/Kevin/`.\n',
    '.claude/CLAUDE.md': '# CLAUDE.md — Claude Code bridge for Kevin\n',
    '.claude/rules/style.md': 'Kevin writes short lines.\n',
    '.claude/skills/mine/SKILL.md': 'Kevin runs this.\n',
    'knowledge/memory/index.md': 'HOME history `~/.local/state/agent-kevin/Documents-Agents-Kevin.git`, said Kevin.\n',
    'knowledge/raw/user/feedback.md': 'Kevin, stop doing that.\n',
    'projects/TASKS.md': '> auto-generated by Kevin\n',
    'projects/acme/README.md': 'Kevin owns this.\n',
    'projects/acme/windows.md': 'Kevin on Windows, home at C:\\Users\\ada\\Agents\\Kevin.\r\nAsk Kevin.\r\n',
    'reports/briefings/2026-01-01.md': 'Kevin briefed.\n',
    'archive/old/README.md': 'Kevin archived this.\n',
    'projects/acme/archive/notes.md': 'Kevin archived this too.\n',
    'knowledge/memory/archive/decisions.md': 'Kevin decided.\n',
    'projects/acme/bot.ts': "const prompt = 'You are Kevin';\n",
    'projects/acme/letter.html': '<p>Signed, Kevin</p>\n',
    ...files
  };
  for (const [rel, content] of Object.entries(all)) {
    mkdirSync(join(root, rel, '..'), { recursive: true });
    writeFileSync(join(root, rel), content);
  }
  const run = (...args: string[]) => {
    const proc = spawnSync(process.execPath, [SCRIPT, '--home', root, ...args]);
    return {
      status: proc.status,
      stderr: proc.stderr.toString(),
      json: proc.status === 2 ? null : JSON.parse(proc.stdout.toString())
    };
  };
  const read = (rel: string) => readFileSync(join(root, rel), 'utf-8');
  return { root, run, read };
};

describe('rename-agent', () => {
  test('a dry run reports every line and writes nothing', () => {
    const { run, read } = home();
    const { status, json } = run('--to', 'Vega');
    expect(status).toBe(0);
    expect(json.mode).toBe('dry-run');
    expect(json.hits.map((hit: { path: string }) => hit.path)).toEqual([
      'SOUL.md',
      'IDENTITY.md',
      'AGENTS.md',
      '.claude/CLAUDE.md',
      '.claude/rules/style.md',
      'knowledge/memory/index.md',
      'projects/acme/README.md',
      'projects/acme/windows.md',
      'projects/acme/windows.md'
    ]);
    expect(json.guarded.map((hit: { path: string }) => hit.path)).toEqual(['AGENTS.md']);
    expect(json.identity).toEqual({ name: 'Kevin → Vega', formerly: 'Kevin' });
    expect(json.manual).toEqual([{ path: '.claude/skills/mine/SKILL.md', line: 1, text: 'Kevin runs this.' }]);
    expect(read('SOUL.md')).toBe("You are Kevin. Kevin's rules.\n");
  });

  test('apply renames current docs, keeps paths, history and kept lines, and records the old name', () => {
    const { run, read } = home();
    const { status, json } = run('--to', 'Vega', '--keep', 'IDENTITY.md:7', '--apply');
    expect(status).toBe(0);
    expect(json.changed.sort()).toEqual([
      '.claude/CLAUDE.md',
      '.claude/rules/style.md',
      'AGENTS.md',
      'IDENTITY.md',
      'SOUL.md',
      'knowledge/memory/index.md',
      'projects/acme/README.md',
      'projects/acme/windows.md'
    ]);
    expect(read('IDENTITY.md')).toBe(
      '# Identity\n\n## Who\n\n- **Name:** Vega\n- **Formerly:** Kevin\n- **Emoji:** 🍌\n- **Vibe:** Inspired by the minion Kevin.\n'
    );
    expect(read('SOUL.md')).toBe("You are Vega. Vega's rules.\n");
    expect(read('AGENTS.md')).toBe('# Vega\n\nHome at `~/Documents/Agents/Kevin/`.\n');
    expect(read('.claude/CLAUDE.md')).toBe('# CLAUDE.md — Claude Code bridge for Vega\n');
    expect(read('.claude/rules/style.md')).toBe('Vega writes short lines.\n');
    expect(read('knowledge/memory/index.md')).toBe(
      'HOME history `~/.local/state/agent-kevin/Documents-Agents-Kevin.git`, said Vega.\n'
    );
    expect(read('projects/acme/README.md')).toBe('Vega owns this.\n');
    expect(read('projects/acme/windows.md')).toBe(
      'Vega on Windows, home at C:\\Users\\ada\\Agents\\Kevin.\r\nAsk Vega.\r\n'
    );
    for (const rel of [
      '.claude/skills/mine/SKILL.md',
      'knowledge/raw/user/feedback.md',
      'projects/TASKS.md',
      'reports/briefings/2026-01-01.md',
      'archive/old/README.md',
      'projects/acme/archive/notes.md',
      'knowledge/memory/archive/decisions.md',
      'projects/acme/bot.ts',
      'projects/acme/letter.html'
    ]) {
      expect(read(rel)).toContain('Kevin');
    }
  });

  test("a file that isn't UTF-8 is left whole rather than re-encoded", () => {
    const latin1 = Buffer.from('Kevin caf\xe9\n', 'latin1');
    const { run, root } = home({ 'projects/acme/notes.md': latin1 });
    expect(run('--to', 'Vega', '--apply').status).toBe(0);
    expect(readFileSync(join(root, 'projects/acme/notes.md'))).toEqual(latin1);
  });

  test('a CRLF IDENTITY.md keeps CRLF on the lines it gains', () => {
    const { run, read } = home({ 'IDENTITY.md': '# Identity\r\n\r\n- **Name:** Kevin\r\n- **Emoji:** 🍌\r\n' });
    run('--to', 'Vega', '--apply');
    expect(read('IDENTITY.md')).toBe(
      '# Identity\r\n\r\n- **Name:** Vega\r\n- **Formerly:** Kevin\r\n- **Emoji:** 🍌\r\n'
    );
  });

  test('a new name that contains the old one is never renamed twice', () => {
    const { run, read } = home();
    expect(run('--to', 'Kevin Prime', '--apply').status).toBe(0);
    expect(read('SOUL.md')).toBe("You are Kevin Prime. Kevin Prime's rules.\n");
    run('--to', 'Kevin Prime', '--from', 'Kevin', '--apply');
    expect(read('SOUL.md')).toBe("You are Kevin Prime. Kevin Prime's rules.\n");
  });

  test('--from finishes a half-done rename, and a second run changes nothing', () => {
    const { run, read } = home({ 'IDENTITY.md': '# Identity\n\n## Who\n\n- **Name:** Vega\n' });
    expect(run('--to', 'Vega').stderr).toContain('--from');
    const first = run('--to', 'Vega', '--from', 'Kevin', '--apply');
    expect(first.status).toBe(0);
    expect(read('SOUL.md')).toBe("You are Vega. Vega's rules.\n");
    expect(read('IDENTITY.md')).toBe('# Identity\n\n## Who\n\n- **Name:** Vega\n- **Formerly:** Kevin\n');
    expect(run('--to', 'Vega', '--from', 'Kevin', '--apply').json.changed).toEqual([]);
  });

  test('a second rename extends Formerly, and renaming back takes the name off it', () => {
    const { run, read } = home();
    run('--to', 'Vega', '--apply');
    run('--to', 'Nova', '--apply');
    expect(read('IDENTITY.md')).toContain('- **Name:** Nova\n- **Formerly:** Kevin, Vega\n');
    run('--to', 'Kevin', '--apply');
    expect(read('IDENTITY.md')).toContain('- **Name:** Kevin\n- **Formerly:** Vega, Nova\n');
  });

  test('every mention a hit will rename is in its text, however long the line', () => {
    const line = `- Kevin helps. ${'A long unrelated sentence. '.repeat(8)}Ask Kevin.`;
    const { run } = home({ 'SOUL.md': `${line}\n` });
    expect(run('--to', 'Vega').json.hits[0]).toEqual({ path: 'SOUL.md', line: 1, text: line });
  });

  test("IDENTITY.md's Name line can't be kept: the identity edit owns it", () => {
    const { run, read } = home();
    const { status, stderr } = run('--to', 'Vega', '--keep', 'IDENTITY.md:5', '--apply');
    expect(status).toBe(2);
    expect(stderr).toContain('IDENTITY.md:5');
    expect(read('IDENTITY.md')).toBe(IDENTITY);
  });

  test('a {{AGENT_NAME}} repair shows the identity edit in the dry run', () => {
    const { run } = home({ 'IDENTITY.md': '# Identity\n\n- **Name:** {{AGENT_NAME}}\n' });
    const { json } = run('--to', 'Vega', '--from', 'Kevin');
    expect(json.identity).toEqual({ name: '{{AGENT_NAME}} → Vega', formerly: 'Kevin' });
  });

  test("an IDENTITY.md that isn't UTF-8 stops the run before anything is written", () => {
    const latin1 = Buffer.from('# Identity\n\n- **Name:** Kevin\n- **Vibe:** caf\xe9\n', 'latin1');
    const { run, root, read } = home({ 'IDENTITY.md': latin1 });
    const { status, stderr } = run('--to', 'Vega', '--apply');
    expect(status).toBe(2);
    expect(stderr).toContain('UTF-8');
    expect(readFileSync(join(root, 'IDENTITY.md'))).toEqual(latin1);
    expect(read('SOUL.md')).toContain('Kevin');
  });

  test('a symlinked file or folder is never written through', () => {
    const outside = mkdtempSync(join(tmpdir(), 'rename-agent-outside-'));
    dirs.push(outside);
    writeFileSync(join(outside, 'soul.md'), 'Kevin, shared.\n');
    mkdirSync(join(outside, 'knowledge'));
    writeFileSync(join(outside, 'knowledge', 'notes.md'), 'Kevin, shared too.\n');
    const { run, root } = home();
    rmSync(join(root, 'SOUL.md'));
    symlinkSync(join(outside, 'soul.md'), join(root, 'SOUL.md'));
    rmSync(join(root, 'knowledge'), { recursive: true });
    symlinkSync(join(outside, 'knowledge'), join(root, 'knowledge'));
    expect(run('--to', 'Vega', '--apply').status).toBe(0);
    expect(readFileSync(join(outside, 'soul.md'), 'utf-8')).toBe('Kevin, shared.\n');
    expect(readFileSync(join(outside, 'knowledge', 'notes.md'), 'utf-8')).toBe('Kevin, shared too.\n');
  });

  test('a symlinked IDENTITY.md stops the run before anything is written', () => {
    const outside = mkdtempSync(join(tmpdir(), 'rename-agent-outside-'));
    dirs.push(outside);
    writeFileSync(join(outside, 'IDENTITY.md'), IDENTITY);
    const { run, root, read } = home();
    rmSync(join(root, 'IDENTITY.md'));
    symlinkSync(join(outside, 'IDENTITY.md'), join(root, 'IDENTITY.md'));
    const { status, stderr } = run('--to', 'Vega', '--apply');
    expect(status).toBe(2);
    expect(stderr).toContain('symlink');
    expect(read('SOUL.md')).toContain('Kevin');
  });

  test('a --keep that matches no line stops the run before anything is written', () => {
    const { run, read } = home();
    const { status, stderr } = run('--to', 'Vega', '--keep', 'IDENTITY.md:99', '--apply');
    expect(status).toBe(2);
    expect(stderr).toContain('IDENTITY.md:99');
    expect(read('SOUL.md')).toContain('Kevin');
  });

  test('a name outside the allowlist is refused before anything is written', () => {
    const { run, read } = home();
    const { status, stderr } = run('--to', 'Ve$ga', '--apply');
    expect(status).toBe(2);
    expect(stderr).toContain('must match');
    expect(read('SOUL.md')).toContain('Kevin');
  });
});
