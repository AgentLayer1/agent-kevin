#!/usr/bin/env bun
/**
 * Upgrade migration for v0.8.0: env keys carry only the shared `AGENT_*` names, and the guards left
 * for the pre-0.7.0 data dir go.
 *
 * Before 0.8.0 a key under the plugin's own prefix (`KEVIN_*` for agent-kevin) outranked its
 * `AGENT_*` twin. The plugin now reads `AGENT_*` alone, so the home's legacy keys are renamed
 * before they go dark:
 * - `.claude/settings.json` and `settings.local.json`: `env` keys, and `$KEVIN_X` references in any
 *   string (a permission rule, a hook);
 * - `<data dir>/secrets/.env`: key names, line by line, keeping values, comments, order and mode;
 * - `.mcp.json`: `$KEVIN_X`, `${KEVIN_X}` and `$env:KEVIN_X` references and server `env` keys, after
 *   which the configure-skills home fallback collapses to a single `AGENT_HOME` read.
 * When both spellings are set the legacy value wins, since it was the one in effect. Legacy keys in
 * the user-level Claude settings are listed for the operator and never edited. The Codex config is
 * regenerated by the upgrade's codex wiring step.
 *
 * The agent-named `.kevin/` folder moved to `.state/` in 0.7.0 and nothing reads it any more, so the
 * secrets guards init and that move wrote for it (in either settings file's `permissions` and
 * `sandbox`) and its `.gitignore` rules are removed, each matched exactly; a home that still has the
 * folder keeps them, since they protect real files there.
 *
 * Every file is read and planned before any is written, so a file that doesn't parse stops the run
 * with nothing changed. Config backups go under `<data dir>/updates/`; the secrets backup stays inside
 * the secrets store, so no copy of a credential leaves the deny-gated folder. The report names keys,
 * never a value.
 *
 * Run by `/agent-kevin:upgrade` via `run_upgrade` (outside the Bash sandbox, which denies the
 * secrets store). Idempotent.
 * Contract: prints a single-line JSON report as its LAST stdout line; exits non-zero on failure.
 */
import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  statSync,
  writeFileSync
} from 'node:fs';
import { homedir } from 'node:os';
import { basename, join, relative, resolve } from 'node:path';
import { RUNTIME_DIR, isOwnDataDir, legacyEnvPrefix, pluginName } from '../../../mcp-server/src/shared/naming';

const VERSION = '0.8.0';

const HOME = resolve(process.env.AGENT_HOME?.trim() || process.cwd());
const DATA_DIR = resolve(HOME, RUNTIME_DIR);
const SECRETS = resolve(DATA_DIR, 'secrets', '.env');
const PREFIX = legacyEnvPrefix();
const STAMP = new Date().toISOString().replace(/[:.]/g, '-');
const GITIGNORE = resolve(HOME, '.gitignore');
/** The agent-named data dir every home used before 0.7.0, and the guards init and the 0.7.0 move wrote for it. */
const LEGACY_DIR = `.${pluginName().replace(/^agent-/, '')}`;
const LEGACY_SECRETS = `${LEGACY_DIR}/secrets`;
const LEGACY_RULES = new Set([
  `Read(//**/${LEGACY_SECRETS}/**)`,
  `Read(**/${LEGACY_SECRETS}/**)`,
  LEGACY_SECRETS,
  `**/${LEGACY_SECRETS}/**`
]);
const LEGACY_IGNORES = new Set([
  `${LEGACY_DIR}/`,
  `${LEGACY_DIR}/*`,
  `!${LEGACY_DIR}/knowledge.json`,
  `!${LEGACY_DIR}/version.json`
]);
/** A home that still has the old folder keeps its guards: they protect real files there. */
const LEGACY_DIR_PRESENT = existsSync(resolve(HOME, LEGACY_DIR));
const USER_SETTINGS = join(process.env.CLAUDE_CONFIG_DIR?.trim() || join(homedir(), '.claude'), 'settings.json');

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

const isLegacy = (key: string): boolean => key.startsWith(PREFIX) && key.length > PREFIX.length;

const sharedName = (key: string): string => `AGENT_${key.slice(PREFIX.length)}`;

/** Writes the file a symlink points at through a temp file, keeping its mode (the secrets file is 0600). */
const writeAtomic = (file: string, text: string): void => {
  const target = realpathSync(file);
  const temp = `${target}.${process.pid}.tmp`;
  const mode = statSync(target).mode & 0o777;
  writeFileSync(temp, text, { mode });
  chmodSync(temp, mode);
  renameSync(temp, target);
};

const REFERENCE = new RegExp(`(\\$\\{env:|\\$\\{|\\$env:|\\$)${PREFIX}([A-Za-z0-9_]+)`, 'g');

/** Renames legacy references in one string, then drops the home fallback the rename made redundant. */
const renameReferences = (text: string): string =>
  text
    .replace(REFERENCE, (_match, lead: string, rest: string) => `${lead}AGENT_${rest}`)
    .replaceAll('d="$AGENT_HOME"; [ -z "$d" ] && d="$AGENT_HOME";', 'd="$AGENT_HOME";')
    .replaceAll('$d = $env:AGENT_HOME; if (-not $d) { $d = $env:AGENT_HOME };', '$d = $env:AGENT_HOME;');

const renameStrings = (node: unknown): unknown => {
  if (typeof node === 'string') {
    return renameReferences(node);
  }
  if (Array.isArray(node)) {
    return node.map(renameStrings);
  }
  return isRecord(node)
    ? Object.fromEntries(Object.entries(node).map(([key, value]) => [key, renameStrings(value)]))
    : node;
};

interface KeyRename {
  renamed: string[];
  /** `AGENT_*` keys whose value gave way to the legacy twin's. */
  replaced: string[];
}

/**
 * Renames legacy keys in place, order kept; a shadowed `AGENT_*` twin gives way to the legacy value.
 * `shadowedElsewhere` names twins whose legacy key lives in another file of the same merge.
 */
const renameKeys = (
  env: Record<string, unknown>,
  shadowedElsewhere: readonly string[] = []
): KeyRename & { env: Record<string, unknown> } => {
  const renamed = Object.keys(env).filter(isLegacy);
  const replaced = [...new Set([...renamed.map(sharedName), ...shadowedElsewhere])].filter((key) => key in env);
  return {
    env: Object.fromEntries(
      Object.entries(env)
        .filter(([key]) => !replaced.includes(key))
        .map(([key, value]) => [isLegacy(key) ? sharedName(key) : key, value])
    ),
    renamed,
    replaced
  };
};

const readJsonObject = (file: string): Record<string, unknown> => {
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(file, 'utf-8'));
  } catch {
    // The parser's own message can quote the text it choked on, which may be a token.
    throw new Error(`${file} is not valid JSON; fix it, then run the upgrade again`);
  }
  if (!isRecord(parsed)) {
    throw new Error(`${file} is not a JSON object`);
  }
  return parsed;
};

/** A file's new text and what the report says about it. */
interface Rewrite<Report> {
  file: string;
  text: string;
  report: Report;
}

const jsonRewrite = <Report>(
  file: string,
  before: Record<string, unknown>,
  after: Record<string, unknown>,
  report: Report
): Rewrite<Report> | null =>
  JSON.stringify(before) === JSON.stringify(after)
    ? null
    : { file, text: `${JSON.stringify(after, null, 2)}\n`, report };

const settingsFile = (name: string): string => resolve(HOME, '.claude', name);

const readIfPresent = (file: string): Record<string, unknown> | null =>
  existsSync(file) ? readJsonObject(file) : null;

const planSettings = (
  name: string,
  shadowedElsewhere: readonly string[]
): Rewrite<KeyRename & { file: string; pruned: string[] }> | null => {
  const file = settingsFile(name);
  const settings = readIfPresent(file);
  if (!settings) {
    return null;
  }
  const referenced = renameStrings(settings) as Record<string, unknown>;
  const keys = isRecord(referenced.env) ? renameKeys(referenced.env, shadowedElsewhere) : null;
  const guarded = pruneLegacyRules(keys ? { ...referenced, env: keys.env } : referenced);
  return jsonRewrite(file, settings, guarded.settings, {
    file: relative(HOME, file),
    renamed: keys?.renamed ?? [],
    replaced: keys?.replaced ?? [],
    pruned: guarded.pruned
  });
};

const isLegacyRule = (entry: unknown): boolean =>
  typeof entry === 'string'
    ? LEGACY_RULES.has(entry)
    : isRecord(entry) && entry.path === LEGACY_SECRETS && entry.mode === 'deny' && Object.keys(entry).length === 2;

const legacyRulesIn = (node: unknown): string[] => {
  if (Array.isArray(node)) {
    return node.flatMap((entry) =>
      isLegacyRule(entry) ? [typeof entry === 'string' ? entry : JSON.stringify(entry)] : legacyRulesIn(entry)
    );
  }
  return isRecord(node) ? Object.values(node).flatMap(legacyRulesIn) : [];
};

const withoutLegacyRules = (node: unknown): unknown => {
  if (Array.isArray(node)) {
    return node.filter((entry) => !isLegacyRule(entry)).map(withoutLegacyRules);
  }
  return isRecord(node)
    ? Object.fromEntries(Object.entries(node).map(([key, value]) => [key, withoutLegacyRules(value)]))
    : node;
};

/** The legacy secrets guards in a settings file's `permissions` and `sandbox`; nothing else is touched. */
const pruneLegacyRules = (
  settings: Record<string, unknown>
): { settings: Record<string, unknown>; pruned: string[] } => {
  if (LEGACY_DIR_PRESENT) {
    return { settings, pruned: [] };
  }
  const scopes = (['permissions', 'sandbox'] as const).filter((key) => key in settings);
  return {
    settings: { ...settings, ...Object.fromEntries(scopes.map((key) => [key, withoutLegacyRules(settings[key])])) },
    pruned: scopes.flatMap((key) => legacyRulesIn(settings[key]))
  };
};

/**
 * The old data dir's `.gitignore` rules, with the old template's comment when it sits directly above
 * them; a blank line left doubled by the removal goes too.
 */
const planGitignore = (): Rewrite<{ file: string; pruned: string[] }> | null => {
  if (LEGACY_DIR_PRESENT || !existsSync(GITIGNORE)) {
    return null;
  }
  const lines = readFileSync(GITIGNORE, 'utf-8').split('\n');
  const rules = lines.flatMap((line, index) => (LEGACY_IGNORES.has(line.trim()) ? [index] : []));
  if (rules.length === 0) {
    return null;
  }
  const first = rules[0];
  const last = rules[rules.length - 1];
  const commentTop = lines.slice(0, first).findLastIndex((line) => !line.trim().startsWith('#')) + 1;
  const comment = commentTop < first && /^# runtime state/.test(lines[commentTop].trim()) ? commentTop : first;
  const isBlank = (index: number): boolean => (lines[index] ?? '').trim() === '';
  const doubled = isBlank(comment - 1) && isBlank(last + 1) && last + 1 < lines.length - 1 ? [last + 1] : [];
  const dropped = new Set([
    ...rules,
    ...Array.from({ length: first - comment }, (_, offset) => comment + offset),
    ...doubled
  ]);
  return {
    file: GITIGNORE,
    text: lines.filter((_, index) => !dropped.has(index)).join('\n'),
    report: { file: '.gitignore', pruned: rules.map((index) => lines[index].trim()) }
  };
};

const planMcp = (): Rewrite<{ file: string; servers: string[] }> | null => {
  const file = resolve(HOME, '.mcp.json');
  const config = readIfPresent(file);
  if (!config || !isRecord(config.mcpServers)) {
    return null;
  }
  const servers = config.mcpServers;
  const nextServers = Object.fromEntries(
    Object.entries(servers).map(([name, server]) => {
      const referenced = renameStrings(server);
      return [
        name,
        isRecord(referenced) && isRecord(referenced.env)
          ? { ...referenced, env: renameKeys(referenced.env).env }
          : referenced
      ];
    })
  );
  const changed = Object.keys(servers).filter(
    (name) => JSON.stringify(servers[name]) !== JSON.stringify(nextServers[name])
  );
  return jsonRewrite(file, config, { ...config, mcpServers: nextServers }, { file: '.mcp.json', servers: changed });
};

/** A line's key exactly as the plugin's secrets loader reads it, so only a key it used is renamed. */
const keyOf = (line: string): string | undefined => {
  const trimmed = line.trim();
  const eq = trimmed.indexOf('=');
  return trimmed.startsWith('#') || eq <= 0 ? undefined : trimmed.slice(0, eq).trim();
};

const isLegacyKey = (key: string | undefined): key is string =>
  key !== undefined && /^[A-Za-z0-9_]+$/.test(key) && isLegacy(key);

/** `export KEVIN_X=`: the plugin's loader skips it, but a server wrapper that sources the file reads it. */
const exportedKey = (key: string | undefined): string | undefined => {
  const name = key?.match(/^export\s+(\S+)$/)?.[1];
  return isLegacyKey(name) ? name : undefined;
};

/**
 * The secrets file, renamed line by line. A shadowed `AGENT_*` line is dropped, since the legacy value
 * was the one the loader used; the backup keeps it. An `export` line is renamed too, so a sourcing
 * wrapper whose reference was renamed still finds it, but it shadows nothing the loader read.
 */
const planSecrets = (): Rewrite<KeyRename> | null => {
  if (!existsSync(SECRETS)) {
    return null;
  }
  const lines = readFileSync(SECRETS, 'utf-8').split('\n');
  const keys = lines.map(keyOf);
  const loaded = keys.filter(isLegacyKey);
  const exported = keys.map(exportedKey).filter((name): name is string => name !== undefined);
  const renamed = [...new Set([...loaded, ...exported])];
  if (renamed.length === 0) {
    return null;
  }
  const shadowed = new Set(loaded.map(sharedName));
  const text = lines
    .flatMap((line, index) => {
      const key = keys[index];
      const name = isLegacyKey(key) ? key : exportedKey(key);
      if (name !== undefined) {
        return [line.replace(name, () => sharedName(name))];
      }
      return key !== undefined && shadowed.has(key) ? [] : [line];
    })
    .join('\n');
  return { file: SECRETS, text, report: { renamed, replaced: [...shadowed].filter((key) => keys.includes(key)) } };
};

/** Legacy keys the user-level Claude settings set for every home; the operator edits that file, never this script. */
const userLevelKeys = (): string[] => {
  try {
    const env = readIfPresent(USER_SETTINGS)?.env;
    return isRecord(env) ? Object.keys(env).filter(isLegacy) : [];
  } catch {
    return [];
  }
};

const migrate = () => {
  if (!isOwnDataDir(DATA_DIR)) {
    return { action: 'no-data-dir' };
  }
  // A legacy key outranked its twin whichever settings file held each, so the shared file's legacy keys
  // shadow the local file's `AGENT_*` twins too (the local file wins a plain merge).
  const sharedEnv = readIfPresent(settingsFile('settings.json'))?.env;
  const sharedLegacy = isRecord(sharedEnv) ? Object.keys(sharedEnv).filter(isLegacy).map(sharedName) : [];
  const settings = [planSettings('settings.json', []), planSettings('settings.local.json', sharedLegacy)].filter(
    (rewrite) => rewrite !== null
  );
  const mcp = planMcp();
  const gitignore = planGitignore();
  const secrets = planSecrets();
  const configRewrites = [...settings, ...(mcp ? [mcp] : []), ...(gitignore ? [gitignore] : [])];
  const backups = resolve(DATA_DIR, 'updates', `${VERSION}-${STAMP}`);
  if (configRewrites.length > 0) {
    mkdirSync(backups, { recursive: true });
  }
  configRewrites.forEach(({ file, text }) => {
    copyFileSync(file, resolve(backups, basename(file)));
    writeAtomic(file, text);
  });
  if (secrets) {
    const backup = `${SECRETS}.${VERSION}-${STAMP}.bak`;
    copyFileSync(SECRETS, backup);
    chmodSync(backup, 0o600);
    writeAtomic(SECRETS, secrets.text);
  }
  const userKeys = userLevelKeys();
  return {
    action: configRewrites.length > 0 || secrets ? 'migrated' : 'none',
    settings: settings.map(({ report }) => report),
    secrets: secrets?.report ?? null,
    mcp: mcp?.report ?? null,
    gitignore: gitignore?.report ?? null,
    ...(LEGACY_DIR_PRESENT ? { legacyDirKept: LEGACY_DIR } : {}),
    manual: userKeys.length > 0 ? [{ file: USER_SETTINGS, keys: userKeys }] : []
  };
};

try {
  process.stdout.write(JSON.stringify({ ok: true, version: VERSION, home: HOME, ...migrate() }) + '\n');
} catch (err) {
  const message = err instanceof Error ? err.message : String(err);
  process.stdout.write(JSON.stringify({ ok: false, version: VERSION, error: message }) + '\n');
  process.exit(1);
}
