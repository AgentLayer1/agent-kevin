#!/usr/bin/env bun
/**
 * Upgrade migration for v0.7.4: env keys carry only the shared `AGENT_*` names.
 *
 * Before 0.7.4 a key under the plugin's own prefix (`KEVIN_*` for agent-kevin) outranked its
 * `AGENT_*` twin. The plugin now reads `AGENT_*` alone, so every legacy key the home holds is
 * renamed before it goes dark:
 * - `.claude/settings.json` and `settings.local.json`: `env` keys, and `$KEVIN_X` references in any
 *   string (a permission rule, a hook);
 * - `<data dir>/secrets/.env`: key names, line by line, keeping values, comments, order and mode;
 * - `.mcp.json`: `$KEVIN_X`, `${KEVIN_X}` and `$env:KEVIN_X` references and server `env` keys, after
 *   which the configure-skills home fallback collapses to a single `AGENT_HOME` read.
 * When both spellings are set the legacy value wins, since it was the one in effect. Keys set
 * machine-wide (user-level Claude settings, shell profiles) are listed for the operator and never
 * edited. The Codex config is regenerated by the upgrade's codex wiring step.
 *
 * Every rewritten file is backed up first: config under `<data dir>/updates/`, the secrets file
 * inside the secrets store, so no copy of a credential leaves the deny-gated folder. The report
 * names keys, never a value.
 *
 * Run by `/agent-kevin:upgrade` via `run_upgrade` (outside the Bash sandbox, which denies the
 * secrets store). Idempotent.
 * Contract: prints a single-line JSON report as its LAST stdout line; exits non-zero on failure.
 */
import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  statSync,
  writeFileSync
} from 'node:fs';
import { homedir } from 'node:os';
import { basename, join, relative, resolve } from 'node:path';
import { RUNTIME_DIR, isOwnDataDir, legacyEnvPrefix } from '../../../mcp-server/src/shared/naming';

const VERSION = '0.7.4';

const HOME = resolve(process.env.AGENT_HOME?.trim() || process.cwd());
const DATA_DIR = resolve(HOME, RUNTIME_DIR);
const SECRETS = resolve(DATA_DIR, 'secrets', '.env');
const PREFIX = legacyEnvPrefix();
const STAMP = new Date().toISOString().replace(/[:.]/g, '-');
const USER_HOME = process.env.HOME?.trim() || homedir();
const CLAUDE_DIR = process.env.CLAUDE_CONFIG_DIR?.trim() || join(USER_HOME, '.claude');
const SHELL_PROFILES = ['.zshenv', '.zprofile', '.zshrc', '.bash_profile', '.bashrc', '.profile'];

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

const isLegacy = (key: string): boolean => key.startsWith(PREFIX) && key.length > PREFIX.length;

const sharedName = (key: string): string => `AGENT_${key.slice(PREFIX.length)}`;

/** Writes through a temp file, keeping the original's mode (the secrets file is 0600). */
const writeAtomic = (file: string, text: string): void => {
  const mode = existsSync(file) ? statSync(file).mode & 0o777 : undefined;
  writeFileSync(`${file}.tmp`, text, mode === undefined ? undefined : { mode });
  if (mode !== undefined) {
    chmodSync(`${file}.tmp`, mode);
  }
  renameSync(`${file}.tmp`, file);
};

const backupConfig = (file: string): void => {
  const dir = resolve(DATA_DIR, 'updates', `${VERSION}-${STAMP}`);
  mkdirSync(dir, { recursive: true });
  copyFileSync(file, resolve(dir, basename(file)));
};

const REFERENCE = new RegExp(`(\\$\\{|\\$env:|\\$)${PREFIX}([A-Za-z0-9_]+)`, 'g');

/** Renames legacy references in one string, then drops the home fallback the rename made redundant. */
const renameReferences = (text: string): string =>
  text
    .replace(REFERENCE, (_match, lead: string, rest: string) => `${lead}AGENT_${rest}`)
    .replaceAll('d="$AGENT_HOME"; [ -z "$d" ] && d="$AGENT_HOME";', 'd="$AGENT_HOME";')
    .replaceAll('$d = $env:AGENT_HOME; if (-not $d) { $d = $env:AGENT_HOME };', '$d = $env:AGENT_HOME;');

const renameStrings = (node: unknown): unknown => {
  if (typeof node === 'string') {
    return renameReferences(node);
  }
  if (Array.isArray(node)) {
    return node.map(renameStrings);
  }
  return isRecord(node)
    ? Object.fromEntries(Object.entries(node).map(([key, value]) => [key, renameStrings(value)]))
    : node;
};

interface KeyRename {
  renamed: string[];
  /** `AGENT_*` keys whose value gave way to the legacy twin's. */
  replaced: string[];
}

/**
 * Renames legacy keys in place, order kept; a shadowed `AGENT_*` twin gives way to the legacy value.
 * `shadowedElsewhere` names twins whose legacy key lives in another file of the same merge.
 */
const renameKeys = (
  env: Record<string, unknown>,
  shadowedElsewhere: readonly string[] = []
): KeyRename & { env: Record<string, unknown> } => {
  const renamed = Object.keys(env).filter(isLegacy);
  const replaced = [...renamed.map(sharedName), ...shadowedElsewhere].filter((key) => key in env);
  return {
    env: Object.fromEntries(
      Object.entries(env)
        .filter(([key]) => !replaced.includes(key))
        .map(([key, value]) => [isLegacy(key) ? sharedName(key) : key, value])
    ),
    renamed,
    replaced
  };
};

const readJsonObject = (file: string): Record<string, unknown> => {
  const parsed: unknown = JSON.parse(readFileSync(file, 'utf-8'));
  if (!isRecord(parsed)) {
    throw new Error(`${file} is not a JSON object`);
  }
  return parsed;
};

const writeJsonIfChanged = (file: string, before: Record<string, unknown>, after: Record<string, unknown>): boolean => {
  if (JSON.stringify(before) === JSON.stringify(after)) {
    return false;
  }
  backupConfig(file);
  writeAtomic(file, `${JSON.stringify(after, null, 2)}\n`);
  return true;
};

const settingsFile = (name: string): string => resolve(HOME, '.claude', name);

const legacyEnvKeys = (file: string): string[] => {
  const env = existsSync(file) ? readJsonObject(file).env : undefined;
  return isRecord(env) ? Object.keys(env).filter(isLegacy) : [];
};

const migrateSettings = (name: string, shadowedElsewhere: readonly string[]): (KeyRename & { file: string }) | null => {
  const file = settingsFile(name);
  if (!existsSync(file)) {
    return null;
  }
  const settings = readJsonObject(file);
  const referenced = renameStrings(settings) as Record<string, unknown>;
  const keys = isRecord(referenced.env) ? renameKeys(referenced.env, shadowedElsewhere) : null;
  const next = keys ? { ...referenced, env: keys.env } : referenced;
  return writeJsonIfChanged(file, settings, next)
    ? { file: relative(HOME, file), renamed: keys?.renamed ?? [], replaced: keys?.replaced ?? [] }
    : null;
};

const migrateMcp = (): { file: string; servers: string[] } | null => {
  const file = resolve(HOME, '.mcp.json');
  if (!existsSync(file)) {
    return null;
  }
  const config = readJsonObject(file);
  const servers = isRecord(config.mcpServers) ? config.mcpServers : {};
  const nextServers = Object.fromEntries(
    Object.entries(servers).map(([name, server]) => {
      const referenced = renameStrings(server);
      return [
        name,
        isRecord(referenced) && isRecord(referenced.env)
          ? { ...referenced, env: renameKeys(referenced.env).env }
          : referenced
      ];
    })
  );
  const changed = Object.keys(servers).filter(
    (name) => JSON.stringify(servers[name]) !== JSON.stringify(nextServers[name])
  );
  const next = isRecord(config.mcpServers) ? { ...config, mcpServers: nextServers } : config;
  return writeJsonIfChanged(file, config, next) ? { file: '.mcp.json', servers: changed } : null;
};

const ASSIGNMENT = /^(\s*(?:export\s+)?)([A-Za-z_][A-Za-z0-9_]*)(\s*=)/;

/** The secrets file, renamed line by line; a shadowed `AGENT_*` line is commented out, not deleted. */
const migrateSecrets = (): KeyRename | null => {
  if (!existsSync(SECRETS)) {
    return null;
  }
  const lines = readFileSync(SECRETS, 'utf-8').split('\n');
  const keyOf = (line: string): string | undefined => line.match(ASSIGNMENT)?.[2];
  const renamed = lines.map(keyOf).filter((key): key is string => key !== undefined && isLegacy(key));
  if (renamed.length === 0) {
    return null;
  }
  const shadowed = new Set(renamed.map(sharedName));
  const next = lines.map((line) => {
    const key = keyOf(line);
    if (key !== undefined && isLegacy(key)) {
      return line.replace(
        ASSIGNMENT,
        (_match, lead: string, _key: string, equals: string) => `${lead}${sharedName(key)}${equals}`
      );
    }
    return key !== undefined && shadowed.has(key) ? `# ${line}` : line;
  });
  const backup = `${SECRETS}.${VERSION}-${STAMP}.bak`;
  copyFileSync(SECRETS, backup);
  chmodSync(backup, 0o600);
  writeAtomic(SECRETS, next.join('\n'));
  return { renamed, replaced: [...shadowed].filter((key) => lines.some((line) => keyOf(line) === key)) };
};

const tilde = (file: string): string => (file.startsWith(`${USER_HOME}/`) ? `~/${relative(USER_HOME, file)}` : file);

/** Legacy keys this machine sets outside the home, which only the operator should edit. */
const machineWide = (): { file: string; keys: string[] }[] => {
  const userSettings = join(CLAUDE_DIR, 'settings.json');
  const userEnv = existsSync(userSettings) ? readJsonObject(userSettings).env : undefined;
  const assignment = new RegExp(`\\b(${PREFIX}[A-Za-z0-9_]+)\\s*=`, 'g');
  const found = [
    { file: userSettings, keys: isRecord(userEnv) ? Object.keys(userEnv).filter(isLegacy) : [] },
    ...SHELL_PROFILES.map((name) => join(USER_HOME, name))
      .filter((file) => existsSync(file))
      .map((file) => ({
        file,
        keys: [...new Set([...readFileSync(file, 'utf-8').matchAll(assignment)].map((match) => match[1]))]
      }))
  ];
  return found.filter(({ keys }) => keys.length > 0).map(({ file, keys }) => ({ file: tilde(file), keys }));
};

const migrate = () => {
  if (!isOwnDataDir(DATA_DIR)) {
    return { action: 'no-data-dir' };
  }
  // A legacy key outranked its twin whichever settings file held each, so the shared file's legacy keys
  // shadow the local file's `AGENT_*` twins too (the local file wins a plain merge).
  const sharedLegacy = legacyEnvKeys(settingsFile('settings.json')).map(sharedName);
  const settings = [migrateSettings('settings.json', []), migrateSettings('settings.local.json', sharedLegacy)].filter(
    (entry) => entry !== null
  );
  const secrets = migrateSecrets();
  const mcp = migrateMcp();
  const manual = machineWide();
  const changed = settings.length > 0 || secrets !== null || mcp !== null;
  return { action: changed ? 'renamed' : 'none', settings, secrets, mcp, manual };
};

try {
  process.stdout.write(JSON.stringify({ ok: true, version: VERSION, home: HOME, ...migrate() }) + '\n');
} catch (err) {
  const message = err instanceof Error ? err.message : String(err);
  process.stdout.write(JSON.stringify({ ok: false, version: VERSION, error: message }) + '\n');
  process.exit(1);
}
